-- Schema as it was before Flyway (created once by Hibernate on the school server).
-- On an existing database this file is skipped by baseline-on-migrate.
CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(254) NOT NULL UNIQUE,
    password varchar(255) NOT NULL,
    role varchar(255) NOT NULL CHECK (role IN ('CUSTOMER', 'PROVIDER', 'ADMIN')),
    created_at timestamp(6)
);

CREATE TABLE categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE
);

CREATE TABLE provider_profiles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL UNIQUE REFERENCES users(id),
    name varchar(255),
    description varchar(1000),
    location varchar(255),
    phone varchar(255),
    profile_image varchar(255),
    availability boolean NOT NULL,
    subscription_start timestamp(6) with time zone,
    subscription_end timestamp(6) with time zone,
    subscription_paid boolean NOT NULL DEFAULT false
);

CREATE TABLE services (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id bigint NOT NULL REFERENCES provider_profiles(id),
    category_id bigint NOT NULL REFERENCES categories(id),
    name varchar(150) NOT NULL,
    description varchar(2000) NOT NULL,
    price numeric(12, 2) NOT NULL,
    price_unit varchar(255) NOT NULL CHECK (price_unit IN ('HOUR', 'JOB', 'SQUARE_METER')),
    active boolean NOT NULL,
    version bigint
);

CREATE TABLE orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES users(id),
    provider_id bigint NOT NULL REFERENCES provider_profiles(id),
    service_id bigint NOT NULL REFERENCES services(id),
    scheduled_at timestamp(6) NOT NULL,
    status varchar(255) NOT NULL CHECK (status IN ('PENDING', 'ACCEPTED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED', 'REJECTED')),
    unit_price numeric(12, 2) NOT NULL,
    price_unit varchar(255) NOT NULL CHECK (price_unit IN ('HOUR', 'JOB', 'SQUARE_METER')),
    quantity numeric(8, 2) NOT NULL,
    total_price numeric(18, 2) NOT NULL,
    service_name varchar(150) NOT NULL,
    address varchar(300) NOT NULL,
    note varchar(2000),
    created_at timestamp(6) NOT NULL,
    version bigint
);
CREATE INDEX orders_customer_id_idx ON orders(customer_id);
CREATE INDEX orders_provider_id_idx ON orders(provider_id);
CREATE INDEX services_provider_id_idx ON services(provider_id);
