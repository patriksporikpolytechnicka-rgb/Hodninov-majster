-- Run once on an existing database (school server) before deploying reviews.
-- The app uses ddl-auto=validate there, so it will not create this table itself.
BEGIN;
CREATE TABLE reviews (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL UNIQUE REFERENCES orders(id),
    provider_id bigint NOT NULL REFERENCES provider_profiles(id),
    customer_id bigint NOT NULL REFERENCES users(id),
    rating integer NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment varchar(1000),
    created_at timestamp(6) NOT NULL
);
CREATE INDEX reviews_provider_id_idx ON reviews(provider_id);
COMMIT;
